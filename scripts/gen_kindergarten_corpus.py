def main():
    OUT.mkdir(parents=True, exist_ok=True)
    total = 0
    chars = 0
    for subject, items in CORPUS.items():
        for title, content in items.items():
            folder = OUT / subject
            folder.mkdir(parents=True, exist_ok=True)
            fname = title + ".txt"
            (folder / fname).write_text(content, encoding="utf-8")
            total += 1
            chars += len(content)
            print(f"  {subject}/{fname} ({len(content)} chars)")
    print(f"\n完成: {total} 文件, {chars} 字符")


if __name__ == "__main__":
    main()
